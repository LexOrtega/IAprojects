def mensaje_cambiar_modelo(modelo_elegido, detalle=""):
    return f"""
### El modelo seleccionado no alcanza para esta consulta

El modelo **`{modelo_elegido}`** no pudo responder esta pregunta con el contexto recuperado.

Te cambié al modelo recomendado: **`{MODELO_DEFAULT}`**.

{detalle}
"""


def consultar_front(pregunta_usuario, modelo_elegido):
    if not pregunta_usuario or not pregunta_usuario.strip():
        return (
            gr.update(value="Escribe una pregunta para que pueda ayudarte.", visible=True),
            gr.update(),
        )

    modelo_elegido = modelo_elegido or MODELO_DEFAULT
    pregunta_limpia = pregunta_usuario.strip()

    try:
        respuesta = preguntar(pregunta_limpia, modelo=modelo_elegido)
        return (
            gr.update(value=respuesta, visible=True),
            gr.update(),
        )

    except Exception as e:
        return (
            gr.update(
                value=mensaje_cambiar_modelo(
                    modelo_elegido,
                    f"Detalle técnico: `{e}`",
                ),
                visible=True,
            ),
            gr.update(value=MODELO_DEFAULT),
        )


def limpiar_front():
    return "", gr.update(value="", visible=False)


