# --------------------- Buscadores ---------------------
def buscar_equivalencias(query: str, top_k: int = 10) -> list[dict]:
    """Busca equivalencias por coincidencia de palabras."""
    q = normalizar(query)
    palabras = q.split()
    resultados = []
    for key, eq in idx_equivalencias.items():
        score = sum(1 for p in palabras if p in key)
        if score > 0:
            resultados.append((score, eq))
    resultados.sort(key=lambda x: -x[0])
    return [eq for _, eq in resultados[:top_k]]


def buscar_recetas_por_ingrediente(ingrediente: str, top_k: int = 10) -> list[dict]:
    """Devuelve recetas que contienen el ingrediente."""
    key = normalizar(ingrediente)
    ids = []
    for k, v in idx_ingrediente_a_recetas.items():
        if key in k:
            ids.extend(v)
    ids = list(dict.fromkeys(ids))[:top_k]  # únicos, preservando orden
    return [idx_recetas[i] for i in ids]


def buscar_recetas_por_categoria(categoria: str) -> list[dict]:
    """Devuelve todas las recetas de una categoría."""
    cat = categoria.strip()   # limpiar espacios
    # Aceptar variantes: camelCase, espacios, etc.
    mapa = {
        "desayuno": "desayuno",
        "colacionmatutina": "colacionMatutina",
        "colacion matutina": "colacionMatutina",
        "comida": "comida",
        "cena": "cena",
        "colacionnocturna": "colacionNocturna",
        "colacion nocturna": "colacionNocturna",
    }
    key = normalizar(cat).replace(" ", "")
    cat_real = mapa.get(key) or mapa.get(normalizar(cat))
    if cat_real and cat_real in recetas:
        return [{**r, "categoria": cat_real} for r in recetas[cat_real]]
    return []


def buscar_recetas_por_nombre(nombre: str, top_k: int = 5) -> list[dict]:
    """Busca recetas por coincidencia en el nombre."""
    q = normalizar(nombre)
    palabras = q.split()
    resultados = []
    for rid, r in idx_recetas.items():
        nombre_norm = normalizar(r["nombre"])
        score = sum(1 for p in palabras if p in nombre_norm)
        if score > 0:
            resultados.append((score, r))
    resultados.sort(key=lambda x: -x[0])
    return [r for _, r in resultados[:top_k]]

# --------------------- Formateadores ---------------------
def formatear_equivalencia(eq: dict) -> str:
    return f"- {eq['alimento']}: {eq['cantidad']} (grupo: {eq['grupo']})"


def formatear_receta(r: dict) -> str:
    lines = [f"### {r['nombre']} (id: {r['id']}, categoría: {r.get('categoria','?')})"]
    lines.append("Intercambios: " + ", ".join(f"{k}={v}" for k, v in r["intercambios"].items()))
    lines.append("Ingredientes:")
    for ing in r["ingredientes"]:
        lines.append(f"  - {ing['alimento']} x{ing['cantidadPorcion']} porción(es)")
    lines.append("Preparación:")
    for paso in r["preparacion"]:
        lines.append(f"  - {paso}")
    lines.append(f"Tiempo: {r['tiempo_preparacion_min']} min | Porciones: {r['porciones']}")
    return "\n".join(lines)

# --------------------- Pipeline RAG ---------------------
def recuperar_contexto(pregunta: str) -> tuple[str, list[dict], list[dict]]:
    """
    Devuelve (contexto_texto, recetas_recuperadas, equivalencias_recuperadas)
    """
    q_norm = normalizar(pregunta)
    recetas_rec = []
    eq_rec = []

    # 1) ¿Pregunta por una categoría?
    categorias_detectadas = []
    for cat in ["desayuno", "colacion matutina", "colacionmatutina",
                "comida", "cena", "colacion nocturna", "colacionnocturna"]:
        if cat in q_norm:
            categorias_detectadas.append(cat)
    for cat in categorias_detectadas:
        recetas_rec.extend(buscar_recetas_por_categoria(cat))

    # 2) ¿Pregunta por un ingrediente?
    # Extraemr palabras "contenido" comunes
    stopwords = {"que","con","sin","para","como","receta","recetas","dame",
                 "muestrame","opciones","tengo","puedo","hacer","usar",
                 "el","la","los","las","un","una","de","del","en","y","o",
                 "preparar","preparacion","ingredientes","cantidad","cantidades"}
    palabras = [p for p in q_norm.split() if p not in stopwords and len(p) > 2]

    for p in palabras:
        eqs = buscar_equivalencias(p, top_k=3)
        eq_rec.extend(eqs)
        recs = buscar_recetas_por_ingrediente(p, top_k=5)
        recetas_rec.extend(recs)

    # 3) ¿Pregunta por nombre específico de receta?
    recetas_rec.extend(buscar_recetas_por_nombre(pregunta, top_k=3))

    # Validar que ya se haya visto la receta o equivalencia para evitar duplicados
    vistos = set()
    recetas_final = []
    for r in recetas_rec:
        if r["id"] not in vistos:
            vistos.add(r["id"])
            recetas_final.append(r)

    # Validar que ya se haya visto un tipo de alimento para evitar duplicados
    vistos_eq = set()
    eq_final = []
    for e in eq_rec:
        if e["alimento"] not in vistos_eq:
            vistos_eq.add(e["alimento"])
            eq_final.append(e)

    # Recortar para no saturar el contexto
    recetas_final = recetas_final[:8]
    eq_final = eq_final[:15]

    # Construir texto de contexto
    partes = []
    if eq_final:
        partes.append("EQUIVALENCIAS RELEVANTES:\n" +
                      "\n".join(formatear_equivalencia(e) for e in eq_final))
    if recetas_final:
        partes.append("RECETAS RELEVANTES:\n" +
                      "\n\n".join(formatear_receta(r) for r in recetas_final))

    contexto = "\n\n".join(partes) if partes else "No se encontró contexto relevante."
    return contexto, recetas_final, eq_final

# Funcion principal que responde las preguntas

def preguntar(pregunta: str, modelo: str = "llama-3.1-8b-instant") -> str:
    contexto, recetas_rec, eq_rec = recuperar_contexto(pregunta)

    system_prompt = """Eres un asistente nutricional experto en el plan de alimentación del usuario.
Respondes en español, de forma clara y concisa.
Solo usas la información del CONTEXTO proporcionado. Si algo no está en el contexto, dilo explícitamente.
Cuando des una receta, incluye: nombre, ingredientes con porciones, preparación paso a paso, tiempo estimado e intercambios.
Cuando des equivalencias, indica el alimento, la cantidad y el grupo."""

    user_prompt = f"""CONTEXTO:
{contexto}

PREGUNTA DEL USUARIO:
{pregunta}
"""

    respuesta = client.chat.completions.create(
        model=modelo,
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ],
        temperature=0.3,
        max_tokens=1500,   # si las respuestas son muy largas, aumentar este valor
    )
    return respuesta.choices[0].message.content

